import { createHash } from 'node:crypto';
import { mkdir, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { join } from 'node:path';

/*
 * Bundles SweetAlert2 and the Rosemarry skin into one stylesheet served from /vendor.
 *
 * The dialog is a success message on a single form. Shipping its ~32 kB through the global
 * stylesheet made every page pay for it, and shipping it as a component style would have put it in
 * the contact-us chunk for everyone who merely opens the page. Serving it as a separate file lets
 * contact-us.ts fetch it at the moment a dialog is about to appear, next to the SweetAlert2 chunk
 * it already imports dynamically.
 *
 * The filename carries a content hash so it can be cached indefinitely, and `src/generated`
 * hands the resolved URL to the app.
 */
const OUTPUT_DIR = 'public/vendor';
const sources = [
  'node_modules/sweetalert2/dist/sweetalert2.min.css',
  'src/app/pages/contact-us/contact-dialog-theme.css',
];

const parts = await Promise.all(sources.map((file) => readFile(file, 'utf8')));
const css = parts.join('\n');
const hash = createHash('sha256').update(css).digest('hex').slice(0, 8);
const filename = `dialog-${hash}.css`;

await mkdir(OUTPUT_DIR, { recursive: true });
for (const stale of await readdir(OUTPUT_DIR).catch(() => [])) {
  if (/^dialog-[0-9a-f]{8}\.css$/.test(stale) && stale !== filename) {
    await rm(join(OUTPUT_DIR, stale));
  }
}
await writeFile(join(OUTPUT_DIR, filename), css);

await mkdir('src/generated', { recursive: true });
await writeFile(
  'src/generated/dialog-styles.ts',
  '// Generated by scripts/prepare-dialog-styles.mjs. Do not edit.\n' +
    `export const DIALOG_STYLESHEET_URL = '/vendor/${filename}';\n`,
);

console.log(`Dialog stylesheet: ${filename} (${(css.length / 1024).toFixed(1)} kB).`);
